export async function sendMessageToAgentForUser(session: AuthenticatedUser, input: {
  agentId: string
  content: string
}) {
  const user = session.authMode === 'local' ? await ensureLocalOperatorUser() : await getUserById(session.id)

  if (!user) {
    throw new Error('User record is missing')
  }

  const workspaceContext = await getWorkspaceForUser(user.id)

  if (!workspaceContext?.workspace || !workspaceContext.project) {
    throw new Error('Workspace setup has not been completed yet')
  }

  const pool = getPostgresPool()
  const agentResult = await pool.query<AgentRow>(
    `
      SELECT
        id,
        workspace_id,
        project_id,
        openclaw_agent_id,
        name,
        role,
        department,
        workspace_path,
        is_core,
        created_at,
        updated_at
      FROM amp.agents
      WHERE id = $1
        AND workspace_id = $2
    `,
    [input.agentId, workspaceContext.workspace.id],
  )

  const agent = agentResult.rows[0]

  if (!agent) {
    throw new Error('Agent not found')
  }

  const content = input.content.trim()

  if (!content) {
    throw new Error('Message content is required')
  }

  const sessionKey = getCanonicalSessionKey(agent.openclaw_agent_id)
  const userMessageId = randomUUID()
  const runId = randomUUID()

  await pool.query(
    `
      INSERT INTO amp.messages (
        id,
        workspace_id,
        project_id,
        agent_id,
        session_key,
        role,
        content
      )
      VALUES ($1, $2, $3, $4, $5, 'user', $6)
    `,
    [userMessageId, workspaceContext.workspace.id, workspaceContext.project.id, agent.id, sessionKey, content],
  )

  await pool.query(
    `
      INSERT INTO amp.runs (
        id,
        workspace_id,
        project_id,
        agent_id,
        session_key,
        status,
        prompt_excerpt
      )
      VALUES ($1, $2, $3, $4, $5, 'running', $6)
    `,
    [runId, workspaceContext.workspace.id, workspaceContext.project.id, agent.id, sessionKey, trimExcerpt(content)],
  )

  await recordWorkspaceEvent({
    workspaceId: workspaceContext.workspace.id,
    type: 'message.created',
    entityType: 'message',
    entityId: userMessageId,
    payload: {
      agentId: agent.id,
      role: 'user',
      sessionKey,
    },
  })
  await recordWorkspaceEvent({
    workspaceId: workspaceContext.workspace.id,
    type: 'run.updated',
    entityType: 'run',
    entityId: runId,
    payload: {
      runId,
      agentId: agent.id,
      status: 'running',
      sessionKey,
    },
  })
  void publishRunRequested({
    runId,
    workspaceId: workspaceContext.workspace.id,
    projectId: workspaceContext.project.id,
    agentId: agent.id,
    sessionKey,
  }).catch((error) => {
    logger.warn('Run queue publish failed', {
      error: error instanceof Error ? error.message : String(error),
      runId,
    })
  })

  try {
    const result = await sendGatewayChatMessage({
      sessionKey,
      agentId: agent.openclaw_agent_id,
      message: content,
      timeoutMs: 90_000,
    })

    const latestAssistant = [...result.history]
      .reverse()
      .find((entry) => extractRoleFromUnknown(entry) === 'assistant')
    const assistantContent = extractTextFromUnknown(latestAssistant) || 'The run completed, but no assistant reply text was captured.'
    const assistantMessageId = randomUUID()

    await pool.query(
      `
        INSERT INTO amp.messages (
          id,
          workspace_id,
          project_id,
          agent_id,
          session_key,
          role,
          content
        )
        VALUES ($1, $2, $3, $4, $5, 'assistant', $6)
      `,
      [assistantMessageId, workspaceContext.workspace.id, workspaceContext.project.id, agent.id, sessionKey, assistantContent],
    )
    await pool.query(
      `
        UPDATE amp.runs
        SET
          status = 'completed',
          response_excerpt = $2,
          finished_at = NOW(),
          updated_at = NOW()
        WHERE id = $1
      `,
      [runId, trimExcerpt(assistantContent)],
    )

    await recordWorkspaceEvent({
      workspaceId: workspaceContext.workspace.id,
      type: 'message.created',
      entityType: 'message',
      entityId: assistantMessageId,
      payload: {
        agentId: agent.id,
        role: 'assistant',
        sessionKey,
      },
    })
    await recordWorkspaceEvent({
      workspaceId: workspaceContext.workspace.id,
      type: 'run.updated',
      entityType: 'run',
      entityId: runId,
      payload: {
        runId,
        agentId: agent.id,
        status: 'completed',
        sessionKey,
      },
    })
  } catch (error) {
    const message = error instanceof Error ? error.message : 'The gateway request failed'

    await pool.query(
      `
        UPDATE amp.runs
        SET
          status = 'failed',
          error = $2,
          finished_at = NOW(),
          updated_at = NOW()
        WHERE id = $1
      `,
      [runId, message],
    )
    await recordWorkspaceEvent({
      workspaceId: workspaceContext.workspace.id,
      type: 'run.updated',
      entityType: 'run',
      entityId: runId,
      payload: {
        runId,
        agentId: agent.id,
        status: 'failed',
        error: message,
        sessionKey,
      },
    })

    throw error
  }

  return listMessagesForAgentForUser(user, agent.id)
}

