export async function getWorkspaceSnapshotForUser(session: AuthenticatedUser, options?: { agentId?: string }) {
  const user = session.authMode === 'local' ? await ensureLocalOperatorUser() : await getUserById(session.id)

  if (!user) {
    return {
      needsSetup: true,
      authMode: session.authMode,
      user: null,
      workspace: null,
      project: null,
      agents: [],
      tasks: [],
      messages: [],
      runs: [],
      taskEvents: [],
    } satisfies WorkspaceSnapshot
  }

  const workspaceContext = await getWorkspaceForUser(user.id)

  if (!workspaceContext || !workspaceContext.project) {
    return {
      needsSetup: true,
      authMode: user.authMode,
      user,
      workspace: null,
      project: null,
      agents: [],
      tasks: [],
      messages: [],
      runs: [],
      taskEvents: [],
    } satisfies WorkspaceSnapshot
  }

  const [agentRows, taskRows, messageRows, runRows, taskEventRows, liveAgents, liveSessions] = await Promise.all([
    listWorkspaceAgentRows(workspaceContext.workspace.id),
    listWorkspaceTaskRows(workspaceContext.workspace.id),
    listWorkspaceMessageRows(workspaceContext.workspace.id, options?.agentId),
    listWorkspaceRunRows(workspaceContext.workspace.id, options?.agentId),
    listWorkspaceTaskEventRows(workspaceContext.workspace.id),
    listAgents().catch(() => []),
    listSessions().catch(() => []),
  ])

  return {
    needsSetup: false,
    authMode: user.authMode,
    user,
    workspace: workspaceContext.workspace,
    project: workspaceContext.project,
    agents: mergeLiveAgentState(agentRows, liveAgents, liveSessions),
    tasks: taskRows.map(mapTask),
    messages: messageRows.map(mapMessage),
    runs: runRows.map(mapRun),
    taskEvents: taskEventRows.map(mapTaskEvent),
  } satisfies WorkspaceSnapshot
}

export async function bootstrapWorkspaceForUser(session: AuthenticatedUser, input: {
  goal: string
  departments: Department[]
}) {
  await ensureAmpSchema()
  const user = session.authMode === 'local' ? await ensureLocalOperatorUser() : await getUserById(session.id)

  if (!user) {
    throw new Error('User record is missing')
  }

  const existingWorkspace = await getWorkspaceForUser(user.id)

  if (existingWorkspace?.workspace && existingWorkspace.project) {
    return getWorkspaceSnapshotForUser(user)
  }

  const goal = input.goal.trim()

  if (!goal) {
    throw new Error('A workspace goal is required')
  }

  const workspaceId = randomUUID()
  const projectId = randomUUID()
  const requestedDepartments = normalizeDepartments(input.departments)
  const departments = ['core', ...requestedDepartments] as Department[]
  const pool = getPostgresPool()

  await pool.query('BEGIN')

  try {
    await pool.query(
      `
        INSERT INTO amp.workspaces (id, owner_user_id, name, goal)
        VALUES ($1, $2, $3, $4)
      `,
      [workspaceId, user.id, DEFAULT_WORKSPACE_NAME, goal],
    )
    await pool.query(
      `
        INSERT INTO amp.projects (id, workspace_id, name, description)
        VALUES ($1, $2, $3, $4)
      `,
      [projectId, workspaceId, DEFAULT_PROJECT_NAME, DEFAULT_PROJECT_DESCRIPTION],
    )
    await pool.query('COMMIT')
  } catch (error) {
    await pool.query('ROLLBACK')
    throw error
  }

  for (const department of departments) {
    const config = DEPARTMENT_CONFIG[department]
    let openclawAgentId: string = department

    try {
      const created = await createGatewayAgent({
        name: department,
        workspace: config.workspacePath,
      })

      if (created.agentId?.trim()) {
        openclawAgentId = created.agentId.trim()
      }
    } catch (error) {
      logger.warn('Gateway agent creation failed during workspace bootstrap', {
        department,
        error: error instanceof Error ? error.message : String(error),
      })
    }

    const agentId = randomUUID()

    await pool.query(
      `
        INSERT INTO amp.agents (
          id,
          workspace_id,
          project_id,
          openclaw_agent_id,
          name,
          role,
          department,
          workspace_path,
          is_core
        )
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
      `,
      [
        agentId,
        workspaceId,
        projectId,
        openclawAgentId,
        config.name,
        config.role,
        department,
        config.workspacePath,
        Boolean(config.isCore),
      ],
    )

    await ensureGatewaySession(getCanonicalSessionKey(openclawAgentId), openclawAgentId, config.name).catch((error) => {
      logger.warn('Gateway session bootstrap failed during workspace bootstrap', {
        department,
        error: error instanceof Error ? error.message : String(error),
        agentId: openclawAgentId,
      })
    })
  }

  const createdAgents = await listWorkspaceAgentRows(workspaceId)
  const coreAgentRow = createdAgents.find((agent: AgentRow) => agent.department === 'core')

  if (!coreAgentRow) {
    throw new Error('Core planner agent was not created')
  }

  const planner = await createPlannerTasks({
    goal,
    departments: requestedDepartments,
    coreAgentId: coreAgentRow.openclaw_agent_id,
  })

  const agentByDepartment = new Map(createdAgents.map((agent: AgentRow) => [agent.department, agent] as const))

  for (const task of planner.tasks) {
    const assignedAgent = task.assignedDepartment ? agentByDepartment.get(task.assignedDepartment) : null

    await pool.query(
      `
        INSERT INTO amp.tasks (
          id,
          workspace_id,
          project_id,
          assigned_agent_id,
          title,
          description,
          status,
          priority
        )
        VALUES ($1, $2, $3, $4, $5, $6, 'backlog', $7)
      `,
      [
        randomUUID(),
        workspaceId,
        projectId,
        assignedAgent?.id ?? null,
        task.title.trim(),
        task.description?.trim() || null,
        normalizeTaskPriority(task.priority),
      ],
    )
  }

  if (planner.projectSummary.trim()) {
    await pool.query(
      `
        UPDATE amp.projects
        SET description = $2,
            updated_at = NOW()
        WHERE id = $1
      `,
      [projectId, planner.projectSummary.trim()],
    )
  }

  return getWorkspaceSnapshotForUser(user)
}

export async function createWorkspaceAgentForUser(session: AuthenticatedUser, input: {
  projectId: string
  department: Department
  name: string
  role: string
}) {
  const user = session.authMode === 'local' ? await ensureLocalOperatorUser() : await getUserById(session.id)

  if (!user) {
    throw new Error('User record is missing')
  }

  const workspaceContext = await getWorkspaceForUser(user.id)

  if (!workspaceContext?.workspace || !workspaceContext.project) {
    throw new Error('Workspace setup has not been completed yet')
  }

  const name = input.name.trim()
  const role = input.role.trim()

  if (!name) {
    throw new Error('Agent name is required')
  }

  if (!role) {
    throw new Error('Agent role is required')
  }

  if (input.department === 'core') {
    throw new Error('The core planner agent is created during setup and cannot be added manually')
  }

  if (!input.projectId.trim()) {
    throw new Error('Project id is required')
  }

  const project = await getWorkspaceScopedProject(workspaceContext.workspace.id, input.projectId.trim())

  if (!project) {
    throw new Error('Project not found in this workspace')
  }

  const department = input.department
  const requestedAgentId = `${department}-${randomUUID().slice(0, 8)}`
  let openclawAgentId = requestedAgentId
  let workspacePath = `/home/node/.openclaw/workspace/${openclawAgentId}`

  try {
    const created = await createGatewayAgent({
      name: openclawAgentId,
      workspace: workspacePath,
    })

    if (created.agentId?.trim()) {
      openclawAgentId = created.agentId.trim()
      workspacePath = `/home/node/.openclaw/workspace/${openclawAgentId}`
      logger.info('Gateway agent created', {
        requestedId: requestedAgentId,
        actualId: openclawAgentId,
      })
    }
  } catch (error) {
    logger.warn('Gateway agent creation failed', {
      error: error instanceof Error ? error.message : String(error),
      openclawAgentId,
    })
  }

  const pool = getPostgresPool()
  const agentId = randomUUID()
  await pool.query(
    `
      INSERT INTO amp.agents (
        id,
        workspace_id,
        project_id,
        openclaw_agent_id,
        name,
        role,
        department,
        workspace_path,
        is_core
      )
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8, FALSE)
    `,
    [
      agentId,
      workspaceContext.workspace.id,
      project.id,
      openclawAgentId,
      name,
      role,
      department,
      workspacePath,
    ],
  )

  await ensureGatewaySession(getCanonicalSessionKey(openclawAgentId), openclawAgentId, name).catch((error) => {
    logger.warn('Gateway session bootstrap failed for created agent', {
      error: error instanceof Error ? error.message : String(error),
      agentId: openclawAgentId,
    })
  })

  await recordWorkspaceEvent({
    workspaceId: workspaceContext.workspace.id,
    type: 'agent.created',
    entityType: 'agent',
    entityId: agentId,
    payload: {
      agentId,
      openclawAgentId,
      department,
      name,
    },
  })

  return getWorkspaceSnapshotForUser(user)
}

