function normalizeDepartments(departments: unknown[]) {
  const requested = Array.isArray(departments) ? departments : []

  return Array.from(
    new Set(
      requested.filter((value): value is Department => (
        typeof value === 'string'
        && value in DEPARTMENT_CONFIG
        && value !== 'core'
      )),
    ),
  )
}

function normalizeTaskStatus(value: unknown): TaskStatus {
  if (value === 'in_progress' || value === 'blocked' || value === 'done') {
    return value
  }

  return 'backlog'
}

function normalizeTaskPriority(value: unknown): TaskPriority {
  if (value === 'low' || value === 'high') {
    return value
  }

  return 'medium'
}

function trimExcerpt(value: string, maxLength = 280) {
  const compact = value.replace(/\s+/g, ' ').trim()

  if (compact.length <= maxLength) {
    return compact || null
  }

  return `${compact.slice(0, maxLength - 1).trimEnd()}…`
}

