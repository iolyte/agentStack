function buildTaskAuditEntries(input: {
  previousStatus: TaskStatus
  nextStatus: TaskStatus
  previousPriority: TaskPriority
  nextPriority: TaskPriority
  previousAssignedAgentId: string | null
  nextAssignedAgentId: string | null
}) {
  const entries: TaskAuditEntry[] = []

  if (input.previousStatus !== input.nextStatus) {
    entries.push({
      type: 'status_changed',
      previousStatus: input.previousStatus,
      nextStatus: input.nextStatus,
      previousPriority: null,
      nextPriority: null,
      previousAssignedAgentId: null,
      nextAssignedAgentId: null,
    })
  }

  if (input.previousPriority !== input.nextPriority) {
    entries.push({
      type: 'priority_changed',
      previousStatus: null,
      nextStatus: null,
      previousPriority: input.previousPriority,
      nextPriority: input.nextPriority,
      previousAssignedAgentId: null,
      nextAssignedAgentId: null,
    })
  }

  if ((input.previousAssignedAgentId ?? null) !== (input.nextAssignedAgentId ?? null)) {
    entries.push({
      type: 'assignment_changed',
      previousStatus: null,
      nextStatus: null,
      previousPriority: null,
      nextPriority: null,
      previousAssignedAgentId: input.previousAssignedAgentId ?? null,
      nextAssignedAgentId: input.nextAssignedAgentId ?? null,
    })
  }

  return entries
}

function extractTextFromUnknown(value: unknown): string {
  if (typeof value === 'string') {
    return value.trim()
  }

  if (Array.isArray(value)) {
    return value
      .map((entry) => extractTextFromUnknown(entry))
      .filter(Boolean)
      .join('\n')
      .trim()
  }

  if (!value || typeof value !== 'object') {
    return ''
  }

  const record = value as Record<string, unknown>

  return [
    record.visibleText,
    record.text,
    record.content,
    record.message,
    record.body,
    record.output_text,
    record.outputText,
    record.parts,
    record.contentParts,
  ]
    .map((entry) => extractTextFromUnknown(entry))
    .find(Boolean) || ''
}

function extractRoleFromUnknown(value: unknown): WorkspaceMessage['role'] | null {
  if (!value || typeof value !== 'object') {
    return null
  }

  const record = value as Record<string, unknown>
  const rawRole = [record.role, record.kind, record.senderRole].find((entry) => typeof entry === 'string') as string | undefined

  if (rawRole === 'user' || rawRole === 'assistant' || rawRole === 'system') {
    return rawRole
  }

  return null
}

function extractPlannerPayload(reply: string) {
  const fencedMatch = reply.match(/```json\s*([\s\S]*?)```/i)
  const candidate = fencedMatch?.[1] || reply
  const start = candidate.indexOf('{')
  const end = candidate.lastIndexOf('}')

  if (start === -1 || end === -1 || end <= start) {
    return null
  }

  try {
    const parsed = JSON.parse(candidate.slice(start, end + 1)) as {
      projectSummary?: string
      tasks?: PlannerTask[]
    }

    if (!Array.isArray(parsed.tasks)) {
      return null
    }

    return {
      projectSummary: typeof parsed.projectSummary === 'string' ? parsed.projectSummary.trim() : '',
      tasks: parsed.tasks
        .filter((task) => task && typeof task.title === 'string' && task.title.trim() !== '')
        .slice(0, 8),
    }
  } catch {
    return null
  }
}

